// Generates a framework embed's example loaders before `vite` / `vite build` / `tsc`:
//
//   node ../shared/scripts/generate.ts <framework>
//   → examples/<framework>/src/embed/loaders.generated.ts   id → { lazy import, layout }
//
// Git-ignored and rebuilt on every dev start, build and typecheck, so it cannot go stale. The
// file is text for the framework app: this package imports no framework itself.

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { type Framework, isFramework } from "../src/framework.ts";
import {
    type ExampleEntry,
    type ExamplesApp,
    examplesApp,
    loadExamples,
} from "./examples-lib.ts";

/** How each framework names a component type, and how an example's entry is imported. */
const LOADER_TYPES: Record<
    Framework,
    { module: string; type: string; component: string; specifier: string }
> = {
    react: {
        module: "react",
        type: "ComponentType",
        component: "ComponentType",
        specifier: "",
    },
    vue: {
        module: "vue",
        type: "Component",
        component: "Component",
        specifier: "/index.vue",
    },
    angular: {
        module: "@angular/core",
        type: "Type",
        component: "Type<unknown>",
        specifier: "/index",
    },
};

/** The text of `src/embed/loaders.generated.ts` for these examples. */
export function loadersSource(
    framework: Framework,
    examples: ExampleEntry[],
): string {
    const { module, type, component, specifier } = LOADER_TYPES[framework];
    return `// Generated by scripts/generate.ts. Do not edit; it is git-ignored.

import type { ${type} } from "${module}";
import type { ExampleLayout } from "examples-shared/meta-types";

export const LOADERS: Record<
    string,
    { load: () => Promise<{ default: ${component} }>; layout: ExampleLayout }
> = {
${examples
    .map(
        (e) =>
            `    ${JSON.stringify(e.slug)}: {\n        load: () => import("../examples/${e.slug}${specifier}"),\n        layout: ${JSON.stringify(e.meta.layout ?? "fill")},\n    },`,
    )
    .join("\n")}
};
`;
}

export async function generateLoaders(app: ExamplesApp): Promise<number> {
    const examples = await loadExamples(app);
    writeFileSync(
        join(app.src, "embed", "loaders.generated.ts"),
        loadersSource(app.framework, examples),
    );
    return examples.length;
}

if (import.meta.main) {
    const [framework] = process.argv.slice(2);
    if (!isFramework(framework)) {
        console.error("usage: node scripts/generate.ts <react|vue|angular>");
        process.exit(1);
    }
    const count = await generateLoaders(examplesApp(framework));
    console.log(`examples (${framework}): ${count}`);
}
